//! Argo Workflows: a WorkflowTemplate, and `caller/`, the program that runs the tasks dandori
//! writes (`lambda`, `http`, `aws`, `agent`) and the rules, in containers of the workflow.
//!
//! Argo has no variables, no step that ends the workflow early, and no names for errors, so
//! the workflow keeps its own state in its global output parameters:
//!
//! - every variable is a global parameter, `v<n>`, holding its value as JSON; the variables a
//!   parallel round keeps for itself get the round's suffix (`v<n>_p<site>i<index>`);
//! - `dd_ctl` says how the flow goes on: `next`, or `break`, `succeed`, `fail`, `task` (a task's
//!   error nothing handled); `dd_error` holds the error of `fail` and `task`, `dd_output` the
//!   outputs of `succeed`.
//!
//! Argo evaluates a step's `when` and arguments again each time it looks at the workflow while
//! the step runs, and a template of steps reads the global parameters as they were when Argo
//! came to it, not as its own steps have set them since. So the global parameters are read in
//! one place only: the output expressions of a template whose one step never runs, which
//! computes values without a pod. Argo evaluates those once, as it comes to the template,
//! with everything set before. Every other step takes what it needs from such outputs, which
//! stay as they are:
//!
//! - a call's arguments, the arm of a match and the number of a loop's rounds are computed
//!   just before them;
//! - every statement that can stop the flow has an output `go`, and the statements after it
//!   in its block run when it is `true`;
//! - loops run their rounds one at a time with `withSequence` and `parallelism`, not by
//!   recursion, whose depth Argo limits to 100;
//! - a task is a container: the user's image (`image`), or the caller image for the tasks
//!   dandori writes and the rules. The call comes in the environment variable DANDORI_CALL;
//!   the answer goes to /tmp/dandori/answer.json; a declared error goes to
//!   /tmp/dandori/error.json as { "error", "message" }, with exit code 3; a pod stopped at its
//!   deadline (exit code 143 or 137) is a timeout; anything else is a failure. The deadline is
//!   the pod's `activeDeadlineSeconds`, which also stops a pod that never started; a
//!   template's `timeout` that runs out before the pod starts would fail the steps around it,
//!   past `continueOn`.
//!
//! When the flow ends as failed, a last container fails the workflow with the error, which
//! also stays in `dd_error`.

