impl<'a> Gen<'a> {
    fn var(&self, name: &str) -> String {
        format!("s.{}", py_name(name))
    }

    fn expr(&self, e: &TExpr) -> String {
        match e {
            TExpr::Str(s) => q(s),
            TExpr::Int(n) => n.to_string(),
            TExpr::Bool(b) => if *b { "True".into() } else { "False".into() },
            TExpr::Enum(v, _) => q(v),
            TExpr::None(_) => "None".into(),
            TExpr::Var { name, fields, ty } => {
                let mut s = self.var(name);
                for (i, f) in fields.iter().enumerate() {
                    // an absent field reads as None
                    if i + 1 == fields.len() && matches!(ty, Ty::Opt(_)) {
                        s = format!("{s}.get({})", q(f));
                    } else {
                        s = format!("{s}[{}]", q(f));
                    }
                }
                s
            }
            TExpr::Record { fields, .. } => format!("{{{}}}", fields.iter().map(|(f, x)| format!("{}: {}", q(f), self.expr(x))).collect::<Vec<_>>().join(", ")),
            TExpr::List { items, .. } => format!("[{}]", items.iter().map(|x| self.expr(x)).collect::<Vec<_>>().join(", ")),
            TExpr::Interp(parts) => {
                let out: Vec<String> = parts
                    .iter()
                    .map(|p| match p {
                        IPart::Lit(s) => q(s),
                        IPart::Hole(x) => format!("dd.text({})", self.expr(x)),
                    })
                    .collect();
                if out.is_empty() {
                    "\"\"".into()
                } else {
                    format!("({})", out.join(" + "))
                }
            }
        }
    }

    fn rounds_expr(&self) -> String {
        format!("[{}]", self.loops.iter().map(|l| format!("s.dd_loop_{l}")).collect::<Vec<_>>().join(", "))
    }

    fn node(&self, class: String, doc: String, order: (usize, usize), cx: &Ctx) -> Node {
        Node { class, doc, order, body: Vec::new(), targets: Vec::new(), end: cx.end }
    }

    fn field(&mut self, name: String, ty: &str, default: &str) {
        self.fields.insert(name, (ty.to_string(), default.to_string()));
    }

    /// The graph.py: the state, the dependencies, the nodes, the rounds' graphs, and `graph`.
    fn graph(&mut self, header: &str, rules: bool) -> String {
        let m = self.m;
        let flow_cx = |unhandled: Unhandled| Ctx { brk: None, unhandled, end: OUTPUT };
        let entry = match &m.on_failure {
            Some(block) => {
                // `on failure` runs for a task's error nothing took, then the run fails with it
                let mut refail = self.node("DD_refail".into(), "after `on failure`: the run fails with the task's error".into(), (usize::MAX, 0), &flow_cx(Unhandled::Fail));
                refail.line(0, "raise dd.Failure(s.dd_failed[\"kind\"], s.dd_failed[\"message\"])");
                self.nodes.push(refail);
                self.field("dd_failed".into(), "dict[str, Any] | None", "None");
                let on_failure = self.block(block, Jump::Node("DD_refail".into()), &flow_cx(Unhandled::Fail));
                self.block(&m.flow, Jump::End("None".into()), &flow_cx(Unhandled::OnFailure(on_failure)))
            }
            None => self.block(&m.flow, Jump::End("None".into()), &flow_cx(Unhandled::Fail)),
        };
        let first = match &entry {
            Jump::Node(n) => n.clone(),
            Jump::End(_) => {
                let mut done = self.node("DD_done".into(), "the flow does nothing".into(), (0, 0), &flow_cx(Unhandled::Fail));
                done.jump(0, &Jump::End("None".into()));
                self.nodes.push(done);
                "DD_done".into()
            }
        };

        let mut out = header.to_string();
        out.push_str(&format!("# {} v{}{}\n#\n", m.name, m.version, if m.description.is_empty() { String::new() } else { format!(": {}", m.description) }));
        out.push_str("# Run it with the input as a dict:\n#   await graph.run(inputs={…}, state=State(), deps=Deps(tasks=make_tasks(your_tasks), run_id=\"…\"))\n");
        out.push_str("# It returns the outputs (None when the flow ends without `succeed`), or raises runtime.Failure.\n");
        out.push_str("# The run lives in this process: a wait sleeps by Deps.clock, a callback's answer comes to\n# Deps.callbacks. graph.render() draws the flow.\n\n");
        out.push_str("from __future__ import annotations\n\nimport copy\nfrom dataclasses import dataclass, field\nfrom typing import Any\n\n");
        out.push_str("from pydantic_graph import BaseNode, End, GraphBuilder, GraphRunContext, StepContext\n\n");
        out.push_str("from . import runtime as dd\nfrom . import types as T\nfrom .tasks import Tasks\n\n\n");

        // the state: every variable, and where the loops are
        out.push_str("@dataclass\nclass State:\n    \"\"\"The flow's variables, and where its loops are.\"\"\"\n\n");
        for (v, ty) in &m.vars {
            let t = if matches!(ty, Ty::Opt(_)) { py_type(m, ty) } else { format!("{} | None", py_type(m, ty)) };
            out.push_str(&format!("    {}: {t} = None\n", py_name(v)));
        }
        for (n, (t, d)) in &self.fields {
            out.push_str(&format!("    {n}: {t} = {d}\n"));
        }
        if m.vars.is_empty() && self.fields.is_empty() {
            out.push_str("    pass\n");
        }

        out.push_str("\n\n");
        if rules {
            out.push_str("def dd_rules() -> Any:\n    from . import rules\n\n    return rules\n\n\n");
        }
        out.push_str("@dataclass\nclass Deps:\n    \"\"\"What the graph calls and waits by.\"\"\"\n\n");
        out.push_str("    tasks: Tasks\n    \"\"\"make_tasks(your_tasks, transport) of tasks.py\"\"\"\n");
        if rules {
            out.push_str("    rules: Any = field(default_factory=dd_rules)\n    \"\"\"the rules: rules.py, around the Python rulec generates\"\"\"\n");
        }
        out.push_str("    clock: dd.Clock = field(default_factory=dd.Clock)\n");
        out.push_str("    callbacks: dd.Callbacks = field(default_factory=dd.Callbacks)\n");
        out.push_str("    run_id: str = \"run\"\n    \"\"\"names the run in the idempotency keys and the callbacks' ids\"\"\"\n");

        let reach = |nodes: &[Node], from: &str| -> BTreeSet<String> {
            let by: BTreeMap<&str, &Node> = nodes.iter().map(|n| (n.class.as_str(), n)).collect();
            let mut seen = BTreeSet::new();
            let mut stack = vec![from.to_string()];
            while let Some(c) = stack.pop() {
                if !seen.insert(c.clone()) {
                    continue;
                }
                if let Some(n) = by.get(c.as_str()) {
                    for t in &n.targets {
                        if let Jump::Node(x) = t {
                            stack.push(x.clone());
                        }
                    }
                }
            }
            seen
        };
        let emit = |out: &mut String, nodes: &mut Vec<Node>, keep: &BTreeSet<String>| {
            nodes.sort_by_key(|n| n.order);
            for n in nodes.iter().filter(|n| keep.contains(&n.class)) {
                let mut ret: Vec<String> = n
                    .targets
                    .iter()
                    .map(|t| match t {
                        Jump::Node(c) => c.clone(),
                        Jump::End(_) => format!("End[{}]", n.end),
                    })
                    .collect();
                ret.dedup();
                if ret.is_empty() {
                    // a node that only fails: the run ends there
                    ret.push(format!("End[{}]", n.end));
                }
                out.push_str(&format!("\n\n@dataclass\nclass {}(BaseNode[State, Deps, \"{}\"]):\n    \"\"\"{}\"\"\"\n\n", n.class, n.end, n.doc));
                out.push_str(&format!("    async def run(self, ctx: GraphRunContext[State, Deps]) -> {}:\n", ret.join(" | ")));
                out.push_str("        s, deps = ctx.state, ctx.deps\n");
                for l in &n.body {
                    if l.is_empty() {
                        out.push('\n');
                    } else {
                        out.push_str(&format!("        {l}\n"));
                    }
                }
            }
        };

        let mut rounds = std::mem::take(&mut self.rounds);
        for r in &mut rounds {
            let keep = reach(&r.nodes, &r.entry);
            emit(&mut out, &mut r.nodes, &keep);
            let adds: Vec<String> = r.nodes.iter().filter(|n| keep.contains(&n.class)).map(|n| format!("{b}.node({})", n.class, b = format!("dd_{}", r.name))).collect();
            out.push_str(&format!(
                "\n\ndd_{name} = GraphBuilder(name={}, state_type=State, deps_type=Deps, input_type=Any, output_type=Any)\n\n\n@dd_{name}.step\nasync def {name}_begin(ctx: StepContext[State, Deps, Any]) -> {entry}:\n    return {entry}()\n\n\ndd_{name}.add(dd_{name}.edge_from(dd_{name}.start_node).to({name}_begin), {})\n{name} = dd_{name}.build()\n",
                q(&r.name),
                adds.join(", "),
                name = r.name,
                entry = r.entry
            ));
        }
        let mut nodes = std::mem::take(&mut self.nodes);
        let keep = reach(&nodes, &first);
        emit(&mut out, &mut nodes, &keep);

        // the start: the input, checked, into the state
        out.push_str(&format!("\n\ndd_graph = GraphBuilder(name={}, state_type=State, deps_type=Deps, input_type=dict[str, Any], output_type={OUTPUT})\n\n\n", q(&ident(&m.name))));
        out.push_str(&format!("@dd_graph.step\nasync def begin(ctx: StepContext[State, Deps, dict[str, Any]]) -> {first}:\n"));
        out.push_str("    if not T.is_WorkflowInput(ctx.inputs):\n        raise dd.Failure(\"Dandori.BadInput\", \"the execution's input does not have the declared shape\")\n");
        for (i, _) in &m.inputs {
            out.push_str(&format!("    ctx.state.{} = ctx.inputs.get({})\n", py_name(i), q(i)));
        }
        out.push_str(&format!("    return {first}()\n\n\n"));
        let adds: Vec<String> = nodes.iter().filter(|n| keep.contains(&n.class)).map(|n| format!("dd_graph.node({})", n.class)).collect();
        out.push_str(&format!("dd_graph.add(dd_graph.edge_from(dd_graph.start_node).to(begin), {})\ngraph = dd_graph.build()\n", adds.join(", ")));
        out
    }

    /// A block's nodes; the jump to its first node (or `next`, when it has none).
    fn block(&mut self, ss: &[TStmt], next: Jump, cx: &Ctx) -> Jump {
        let mut stmts = Vec::new();
        for s in ss {
            stmts.push(s);
            if matches!(s.kind, TK::Succeed { .. } | TK::Fail { .. } | TK::Break) {
                break;
            }
        }
        let mut j = next;
        for s in stmts.into_iter().rev() {
            j = self.stmt(s, j, cx);
        }
        j
    }

    /// What a task's error that no `on` takes does, in a node, for the error `e`.
    fn unhandled(n: &mut Node, depth: usize, cx: &Ctx) {
        match &cx.unhandled {
            Unhandled::OnFailure(j) => {
                n.line(depth, "s.dd_failed = {\"kind\": e.kind, \"message\": e.message}");
                n.jump(depth, j);
            }
            Unhandled::Fail => n.line(depth, "raise dd.Failure(e.kind, e.message) from None"),
            Unhandled::Raise => n.line(depth, "raise"),
        }
    }

    fn stmt(&mut self, s: &TStmt, next: Jump, cx: &Ctx) -> Jump {
        let m = self.m;
        let site = s.site;
        let line = s.line;
        match &s.kind {
            TK::Pass => next,
            TK::Break => cx.brk.clone().expect("lowering keeps break inside a loop"),
            TK::Assign { name, expr } => {
                let mut n = self.node(format!("S{site}_let"), format!("line {line}: let {name}"), (site, 0), cx);
                let x = self.expr(expr);
                n.line(0, &format!("{} = {x}", self.var(name)));
                n.jump(0, &next);
                self.push(n)
            }
            TK::Wait { seconds } => {
                let mut n = self.node(format!("S{site}_wait"), format!("line {line}: wait {seconds} seconds"), (site, 0), cx);
                n.line(0, &format!("await deps.clock.sleep({seconds})"));
                n.jump(0, &next);
                self.push(n)
            }
            TK::WaitUntil { at } => {
                let mut n = self.node(format!("S{site}_wait_until"), format!("line {line}: wait until {}", at.show()), (site, 0), cx);
                let x = self.expr(at);
                n.line(0, &format!("await dd.wait_until(deps.clock, {x})"));
                n.jump(0, &next);
                self.push(n)
            }
            TK::Succeed { fields } => {
                let mut n = self.node(format!("S{site}_succeed"), format!("line {line}: succeed"), (site, 0), cx);
                let out = if fields.is_empty() { "None".to_string() } else { format!("{{{}}}", fields.iter().map(|(f, e)| format!("{}: {}", q(f), self.expr(e))).collect::<Vec<_>>().join(", ")) };
                n.jump(0, &Jump::End(out));
                self.push(n)
            }
            TK::Fail { error, cause, .. } => {
                let mut n = self.node(format!("S{site}_fail"), format!("line {line}: fail {error}"), (site, 0), cx);
                let c = cause.as_ref().map(|c| self.expr(c)).unwrap_or_else(|| "None".into());
                n.line(0, &format!("raise dd.Failure({}, {c})", q(error)));
                self.push(n)
            }
            TK::Repeat { times, body } => {
                let again = Jump::Node(format!("S{site}_again"));
                self.field(format!("dd_loop_{site}"), "int", "0");
                self.loops.push(site);
                let inner = Ctx { brk: Some(next.clone()), ..cx.clone() };
                let first = self.block(body, again.clone(), &inner);
                self.loops.pop();
                let mut start = self.node(format!("S{site}_repeat"), format!("line {line}: repeat at most {times} times"), (site, 0), cx);
                start.line(0, &format!("s.dd_loop_{site} = 0"));
                start.jump(0, if *times > 0 { &first } else { &next });
                let mut round = self.node(format!("S{site}_again"), format!("line {line}: the next round"), (site, 1), cx);
                round.line(0, &format!("s.dd_loop_{site} += 1"));
                round.line(0, &format!("if s.dd_loop_{site} < {times}:"));
                round.jump(1, &first);
                round.jump(0, &next);
                self.nodes.push(round);
                self.push(start)
            }
            TK::For { var, list, max, parallel: None, body, result, .. } => {
                let again = Jump::Node(format!("S{site}_again"));
                let done = if result.is_some() { Jump::Node(format!("S{site}_done")) } else { next.clone() };
                self.field(format!("dd_loop_{site}"), "int", "0");
                self.field(format!("dd_items_{site}"), "list[Any]", "field(default_factory=list)");
                if result.is_some() {
                    self.field(format!("dd_out_{site}"), "list[Any]", "field(default_factory=list)");
                }
                self.loops.push(site);
                let inner = Ctx { brk: Some(done.clone()), ..cx.clone() };
                let first = self.block(body, again.clone(), &inner);
                self.loops.pop();
                let v = self.var(var);
                let mut start = self.node(format!("S{site}_for"), format!("line {line}: for {var} in {}", list.show()), (site, 0), cx);
                start.line(0, &format!("dd_items = {}", self.expr(list)));
                start.line(0, &format!("if len(dd_items) > {max}:"));
                start.line(1, &format!("raise dd.Failure(\"Dandori.TooManyItems\", {})", q(&format!("line {line}: the list has more than {max} items"))));
                start.line(0, &format!("s.dd_items_{site} = dd_items"));
                if result.is_some() {
                    start.line(0, &format!("s.dd_out_{site} = []"));
                }
                start.line(0, &format!("s.dd_loop_{site} = 0"));
                start.line(0, "if dd_items:");
                start.line(1, &format!("{v} = dd_items[0]"));
                start.jump(1, &first);
                start.jump(0, &done);
                let mut round = self.node(format!("S{site}_again"), format!("line {line}: the next round"), (site, 1), cx);
                if let Some((_, y)) = result {
                    round.line(0, &format!("s.dd_out_{site}.append({})", self.expr(y)));
                }
                round.line(0, &format!("s.dd_loop_{site} += 1"));
                round.line(0, &format!("if s.dd_loop_{site} < len(s.dd_items_{site}):"));
                round.line(1, &format!("{v} = s.dd_items_{site}[s.dd_loop_{site}]"));
                round.jump(1, &first);
                round.jump(0, &done);
                self.nodes.push(round);
                if let Some((r, _)) = result {
                    let mut end = self.node(format!("S{site}_done"), format!("line {line}: what the rounds yielded"), (site, 2), cx);
                    end.line(0, &format!("{} = s.dd_out_{site}", self.var(r)));
                    end.jump(0, &next);
                    self.nodes.push(end);
                }
                self.push(start)
            }
            TK::For { var, list, max, parallel: Some(k), body, result, locals } => {
                // a round is a graph of its own, which runs on a copy of the state
                self.field(format!("dd_loop_{site}"), "int", "0");
                let round_cx = Ctx { brk: None, unhandled: Unhandled::Raise, end: "Any" };
                let outer = std::mem::take(&mut self.nodes);
                let mut yielded = self.node(format!("S{site}_yield"), format!("line {line}: the round's end"), (site, usize::MAX), &round_cx);
                let y = result.as_ref().map(|(_, y)| self.expr(y)).unwrap_or_else(|| "None".into());
                yielded.jump(0, &Jump::End(y));
                self.nodes.push(yielded);
                self.loops.push(site);
                let first = self.block(body, Jump::Node(format!("S{site}_yield")), &round_cx);
                self.loops.pop();
                let round_nodes = std::mem::replace(&mut self.nodes, outer);
                let entry = match first {
                    Jump::Node(n) => n,
                    Jump::End(_) => format!("S{site}_yield"),
                };
                let name = format!("round_{site}");
                self.rounds.push(Round { name: name.clone(), entry, nodes: round_nodes });
                let mut n = self.node(format!("S{site}_for"), format!("line {line}: for {var} in {} in parallel", list.show()), (site, 0), cx);
                n.line(0, &format!("dd_items = {}", self.expr(list)));
                n.line(0, &format!("if len(dd_items) > {max}:"));
                n.line(1, &format!("raise dd.Failure(\"Dandori.TooManyItems\", {})", q(&format!("line {line}: the list has more than {max} items"))));
                n.line(0, "");
                n.line(0, "async def dd_round(dd_item: Any, dd_i: int) -> Any:");
                n.line(1, "r = copy.copy(s)");
                n.line(1, &format!("r.{} = dd_item", py_name(var)));
                for l in locals {
                    if l != var {
                        n.line(1, &format!("r.{} = None", py_name(l)));
                    }
                }
                n.line(1, &format!("r.dd_loop_{site} = dd_i"));
                n.line(1, &format!("return await {name}.run(state=r, deps=deps)"));
                n.line(0, "");
                n.line(0, "try:");
                n.line(1, &format!("dd_res = await dd.rounds(dd_items, dd.at_a_time({k}), dd_round)"));
                n.line(0, "except dd.TaskError as e:");
                Gen::unhandled(&mut n, 1, cx);
                if let Some((r, _)) = result {
                    n.line(0, &format!("{} = dd_res", self.var(r)));
                }
                n.jump(0, &next);
                self.push(n)
            }
            TK::Match { expr, arms } => {
                let x = match expr {
                    TExpr::Var { name, fields, .. } if m.case_index(name).is_some() => {
                        // a case that has not started reads as none
                        let v = self.var(name);
                        let mut s = v.clone();
                        for f in fields {
                            s.push_str(&format!("[{}]", q(f)));
                        }
                        format!("None if {v} is None else {s}")
                    }
                    other => self.expr(other),
                };
                let firsts: Vec<Jump> = arms.iter().map(|a| self.block(&a.body, next.clone(), cx)).collect();
                let mut n = self.node(format!("S{site}_match"), format!("line {line}: match {}", expr.show()), (site, 0), cx);
                n.line(0, &format!("dd_v = {x}"));
                for (a, first) in arms.iter().zip(&firsts) {
                    let mut parts = Vec::new();
                    if a.none {
                        parts.push("dd_v is None".to_string());
                    }
                    if a.some.is_some() {
                        parts.push("dd_v is not None".to_string());
                    }
                    if !a.values.is_empty() {
                        if expr.ty().inner() == &Ty::Bool {
                            for v in &a.values {
                                parts.push(format!("dd_v is {}", if v == "true" { "True" } else { "False" }));
                            }
                        } else {
                            parts.push(format!("dd_v in ({}{})", a.values.iter().map(|v| q(v)).collect::<Vec<_>>().join(", "), if a.values.len() == 1 { "," } else { "" }));
                        }
                    }
                    n.line(0, &format!("if {}:", parts.join(" or ")));
                    if let Some(v) = &a.some {
                        n.line(1, &format!("{} = dd_v", self.var(v)));
                    }
                    n.jump(1, first);
                }
                n.line(0, &format!("raise dd.Failure(\"Dandori.UnexpectedValue\", {})", q(&format!("line {line}: {} took a value that no arm names", expr.show()))));
                self.push(n)
            }
            TK::Call { target, callee, args, handlers } => self.call(s, target.as_ref(), callee, args, handlers, next, cx),
        }
    }

    fn push(&mut self, n: Node) -> Jump {
        let j = Jump::Node(n.class.clone());
        self.nodes.push(n);
        j
    }

    #[allow(clippy::too_many_arguments)]
    fn call(&mut self, s: &TStmt, target: Option<&Target>, callee: &Callee, args: &[(String, TExpr)], handlers: &[THandler], next: Jump, cx: &Ctx) -> Jump {
        let m = self.m;
        let site = s.site;
        let (cname, declared, result_ty) = match callee {
            Callee::Task(t) => {
                let task = &m.tasks[*t];
                (task.name.clone(), task.errors.iter().map(|e| q(&e.name)).collect::<Vec<_>>(), task.result.clone())
            }
            Callee::Rule(r) => (m.rules[*r].name.clone(), vec![], Some(Ty::Record(m.rules[*r].outputs))),
        };
        let firsts: Vec<Jump> = handlers.iter().map(|h| self.block(&h.body, next.clone(), cx)).collect();
        let mut parts: Vec<String> = args.iter().map(|(a, e)| format!("{}: {}", q(a), self.expr(e))).collect();
        if let Callee::Task(t) = callee {
            if m.tasks[*t].key {
                parts.push(format!("\"idempotency_key\": dd.key(deps.run_id, {site}, {})", self.rounds_expr()));
            }
        }
        let rs = retriers(m, callee);
        let declared = format!("[{}]", declared.join(", "));
        let mut n = self.node(format!("S{site}_{}", ident(&cname)), format!("line {}: {cname}", s.line), (site, 0), cx);
        let call = match callee {
            Callee::Rule(r) => format!("lambda: deps.rules.{}({{{}}})", render::rule_activity(&m.rules[*r].name), parts.join(", ")),
            Callee::Task(t) => {
                let task = &m.tasks[*t];
                let f = format!("deps.tasks.{}", method(&task.name));
                if task.callback {
                    let timeout = task.timeout.unwrap_or(86_400);
                    let mut with_id = parts.clone();
                    with_id.push("\"callback_id\": dd_id".into());
                    n.line(0, "dd_n = dd.counter()");
                    n.line(0, "");
                    n.line(0, "async def dd_call() -> Any:");
                    n.line(1, &format!("dd_id = dd.callback_id(deps.run_id, {site}, {}, next(dd_n))", self.rounds_expr()));
                    n.line(1, &format!("await {f}({{{}}})", with_id.join(", ")));
                    n.line(1, &format!("return await dd.await_callback(deps.callbacks, deps.clock, dd_id, {timeout})"));
                    n.line(0, "");
                    "dd_call".to_string()
                } else {
                    let timeout = task.timeout.map(|t| t.to_string()).unwrap_or_else(|| "None".into());
                    format!("lambda: dd.within({f}({{{}}}), {timeout})", parts.join(", "))
                }
            }
        };
        let reads = target.is_some() && result_ty.is_some();
        let invocation = format!("{}await dd.attempt({call}, {rs}, {declared}, deps.clock)", if reads { "dd_r = " } else { "" });
        if handlers.is_empty() && matches!(cx.unhandled, Unhandled::Raise) {
            n.line(0, &invocation);
        } else {
            n.line(0, "try:");
            n.line(1, &invocation);
            n.line(0, "except dd.TaskError as e:");
            for (h, first) in handlers.iter().zip(&firsts) {
                let conds: Vec<String> = h
                    .errors
                    .iter()
                    .map(|x| match x {
                        HErr::Failure => "True".to_string(),
                        HErr::Timeout => "e.kind == \"timeout\"".to_string(),
                        HErr::Declared(d) => format!("e.kind == {}", q(d)),
                    })
                    .collect();
                if conds.iter().any(|c| c == "True") {
                    n.jump(1, first);
                    break;
                }
                n.line(1, &format!("if {}:", conds.join(" or ")));
                n.jump(2, first);
            }
            if !handlers.iter().any(|h| h.errors.contains(&HErr::Failure)) {
                Gen::unhandled(&mut n, 1, cx);
            }
        }
        // the answer: its declared type, and for a case the states it may carry
        let var = match target {
            Some(Target::Let(v)) => Some(self.var(v)),
            Some(Target::Case(c)) => Some(self.var(&m.cases[*c].name)),
            None => None,
        };
        if let (Some(v), Some(ty)) = (var, &result_ty) {
            n.line(0, &format!("if not {}:", py_check(m, "dd_r", ty, "T.", 0)));
            n.line(1, &format!("raise dd.Failure(\"Dandori.BadResponse\", {})", q(&format!("line {}: the answer from {} does not have the declared shape", s.line, cname))));
            if let (Some(Target::Case(c)), Some((_, allowed))) = (target, m.monitors.get(&site)) {
                let field = &m.cases[*c].state_field;
                n.line(0, &format!("if dd_r[{}] not in ({}{}):", q(field), allowed.iter().map(|v| q(v)).collect::<Vec<_>>().join(", "), if allowed.len() == 1 { "," } else { "" }));
                n.line(
                    1,
                    &format!(
                        "raise dd.Failure(\"Dandori.UnexpectedState\", {})",
                        q(&format!("line {}: {} answered with a state the machine does not lead to here (expected one of {})", s.line, cname, allowed.join(", ")))
                    ),
                );
            }
            n.line(0, &format!("{v} = dd_r"));
        }
        n.jump(0, &next);
        self.push(n)
    }
}
