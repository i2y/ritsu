//! The workflow as a graph of pydantic-graph (2.x): a Python package whose `graph` runs the
//! flow in the process that calls it. Every statement is a node (`BaseNode`), and the return
//! type of its `run` names the nodes it can go to, so `graph.render()` draws the flow.
//!
//! - `types.py`, `io.py`, `rules.py`: as for Temporal's Python SDK (`temporal_py.rs`), the
//!   rules as plain functions
//! - `tasks.py`: the tasks; `make_tasks(own, transport)`, where a declared error of a task you
//!   write is raised as `TaskFailure(kind, message)`
//! - `runtime.py`: retries, error kinds, keys, the clock and the answers of callbacks
//! - `graph.py`: `State` (the flow's variables), `Deps` (the tasks, the rules, the clock, the
//!   callbacks' answers, the run's id), the nodes, and `graph`
//!
//! A run lives in the process that runs it: pydantic-graph 2.x keeps no state anywhere else,
//! so a run that the process loses is lost. The waits sleep by `Deps.clock`, and a callback's
//! answer comes to `Deps.callbacks` in the same process. A round of `for … in parallel` is a
//! graph of its own, run inside the loop's node on a copy of the state.

