//! A page as Markdown that GitHub shows as it is, and as one HTML file in ritsu's frame of a page
//! (`docpage`: the head and the palette, light and dark), reading nothing from outside. The head of
//! both names the file the page was drawn from and its SHA-256, as the pages of the other languages
//! do; the two say the same things in the same order. A page another one holds has no head
//! ([`markdown_held`]).
//!
//! Text in a block holds code in backquotes. In Markdown, a `<` that could begin HTML is written
//! `&lt;` outside the code spans and a table's cell has its `|` escaped (as the Markdown of
//! `sekisho doc`, `dandori doc` and `rulec doc`); in HTML, every `&`, `<`, `>`, `"` and `'` is
//! escaped once, and the code spans are `<code>`.

use super::{Block, Page};
use ritsu_base::docpage::{HTML_TAIL, Palette, esc, html_head};
use ritsu_base::text::Lang;

/// Text written as Markdown prose: a `<` that could begin HTML (followed by a letter, `/`, `!` or
/// `?`) is `&lt;` outside the code spans, and a carriage return or a new line is a space.
pub fn prose(s: &str) -> String {
    let cs: Vec<char> = s.replace(['\r', '\n'], " ").chars().collect();
    let mut o = String::with_capacity(s.len());
    let mut i = 0;
    while i < cs.len() {
        if cs[i] == '`' {
            // a code span runs to the next run of as many backquotes; without one, the backquotes
            // are text
            let n = cs[i..].iter().take_while(|c| **c == '`').count();
            let mut j = i + n;
            let mut end = None;
            while j < cs.len() {
                let m = cs[j..].iter().take_while(|c| **c == '`').count();
                if m == n {
                    end = Some(j + m);
                    break;
                }
                j += m.max(1);
            }
            let stop = end.unwrap_or(i + n);
            o.extend(&cs[i..stop]);
            i = stop;
            continue;
        }
        if cs[i] == '<' && cs.get(i + 1).is_some_and(|c| c.is_ascii_alphabetic() || matches!(c, '/' | '!' | '?')) {
            o.push_str("&lt;");
        } else {
            o.push(cs[i]);
        }
        i += 1;
    }
    o
}

/// A cell of a Markdown table: prose, with its `|` kept from ending the cell.
fn cell(s: &str) -> String {
    let p = prose(s);
    if p.is_empty() { " ".to_string() } else { p.replace('|', "\\|") }
}

/// Text with code in backquotes, as HTML.
pub fn inline(s: &str) -> String {
    let mut out = String::new();
    let mut rest = s;
    while let Some(t) = rest.find('`') {
        let after = &rest[t + 1..];
        let Some(j) = after.find('`') else { break };
        out.push_str(&esc(&rest[..t]));
        out.push_str(&format!("<code>{}</code>", esc(&after[..j])));
        rest = &after[j + 1..];
    }
    out.push_str(&esc(rest));
    out
}

/// What the head of a page says it was drawn from, as a Markdown comment.
fn generated(p: &Page) -> String {
    let version = env!("CARGO_PKG_VERSION");
    // `--` ends a comment in HTML
    let file = p.file.replace("--", "- -");
    match p.lang {
        Lang::En => format!(
            "<!-- Generated by ringi {version} from {file} (sha256:{}). This is a read-only rendering; the source of truth is the .ringi file. Edits cannot be carried back. -->\n",
            p.sha
        ),
        Lang::Ja => format!("<!-- ringi {version} が {file}（sha256:{}）から生成したページです。読むためのもので、もとになるのは .ringi のほうです。ここを編集しても .ringi には戻せません。 -->\n", p.sha),
    }
}

/// Whether `c` is kana or kanji: what a code span is spaced from in Japanese.
fn japanese(c: char) -> bool {
    matches!(c as u32, 0x3040..=0x30FF | 0x3400..=0x4DBF | 0x4E00..=0x9FFF | 0x3005)
}

/// Japanese text with a space between a code span and the kana or kanji next to it, as the Japanese
/// of the suite writes it (`` `budget.reserve` を ``): a sentence joins a name and its words without
/// knowing which of them it gets.
pub fn spaced(s: &str) -> String {
    let cs: Vec<char> = s.chars().collect();
    let mut out = String::with_capacity(s.len() + 8);
    let mut in_code = false;
    for (i, &c) in cs.iter().enumerate() {
        if c == '`' {
            if !in_code && i > 0 && japanese(cs[i - 1]) {
                out.push(' ');
            }
            out.push(c);
            if in_code && cs.get(i + 1).is_some_and(|n| japanese(*n)) {
                out.push(' ');
            }
            in_code = !in_code;
            continue;
        }
        out.push(c);
    }
    out
}

/// The page with every text of a Japanese page [`spaced`]; an English page as it is.
fn settled(p: &Page) -> Page {
    if p.lang != Lang::Ja {
        return p.clone();
    }
    let sp = |s: &String| spaced(s);
    let blocks = p
        .blocks
        .iter()
        .map(|b| match b {
            Block::Heading { level, text, id } => Block::Heading { level: *level, text: sp(text), id: id.clone() },
            Block::Para(t) => Block::Para(sp(t)),
            Block::Note(t) => Block::Note(sp(t)),
            Block::List(xs) => Block::List(xs.iter().map(sp).collect()),
            Block::Table { head, rows } => Block::Table { head: head.iter().map(sp).collect(), rows: rows.iter().map(|r| r.iter().map(sp).collect()).collect() },
        })
        .collect();
    Page { title: sp(&p.title), description: p.description.as_ref().map(sp), blocks, ..p.clone() }
}

pub fn markdown(p: &Page) -> String {
    let p = &settled(p);
    let mut out = generated(p);
    out.push_str(&body_md(p, 0));
    out
}

/// The Markdown of a page another one holds (the changes of a file under `ritsu mod diff`, and the
/// pages made of it): no comment naming the file it was drawn from, which the holder names; each
/// heading `deeper` levels down (to the sixth at most), under the holder's own; and a note as a
/// sentence, as the Markdown the holder writes has no quotes.
pub fn markdown_held(p: &Page, deeper: u8) -> String {
    body_md(&settled(p), deeper)
}

fn body_md(p: &Page, deeper: u8) -> String {
    let mut out = format!("{} {}\n", "#".repeat((1 + usize::from(deeper)).min(6)), prose(&p.title));
    if let Some(d) = &p.description {
        out.push_str(&format!("\n{}\n", prose(d)));
    }
    for b in &p.blocks {
        out.push('\n');
        block_md(&mut out, b, deeper);
    }
    out
}

fn block_md(out: &mut String, b: &Block, deeper: u8) {
    match b {
        Block::Heading { level, text, .. } => out.push_str(&format!("{} {}\n", "#".repeat((usize::from(*level) + usize::from(deeper)).min(6)), prose(text))),
        Block::Para(text) => out.push_str(&format!("{}\n", prose(text))),
        Block::Note(text) if deeper > 0 => out.push_str(&format!("{}\n", prose(text))),
        Block::Note(text) => out.push_str(&format!("> {}\n", prose(text))),
        Block::List(items) => {
            for i in items {
                out.push_str(&format!("- {}\n", prose(i)));
            }
        }
        Block::Table { head, rows } => {
            out.push_str(&format!("| {} |\n", head.iter().map(|h| cell(h)).collect::<Vec<_>>().join(" | ")));
            out.push_str(&format!("|{}\n", "---|".repeat(head.len())));
            for r in rows {
                out.push_str(&format!("| {} |\n", r.iter().map(|c| cell(c)).collect::<Vec<_>>().join(" | ")));
            }
        }
    }
}

